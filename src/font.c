/**
  * @brief  Draw a string.
  *
  * Horizontal runs of dots are merged into one rectangle, which keeps the
  * number of draw calls small at large scales.
  *
  * @param  ren Renderer.
  * @param  x Left edge in pixels.
  * @param  y Top edge in pixels.
  * @param  scale Pixel size of one font dot.
  * @param  text NUL terminated string.
  * @param  c Colour.
  *
  * @retval None.
  */
void fnt_draw( SDL_Renderer *ren, float x, float y, int scale,
               const char *text, SDL_Color c )
{
	const uint8_t *g;
	SDL_FRect r;
	int ch, row, col, run;

	SDL_SetRenderDrawColor( ren, c.r, c.g, c.b, c.a );
	for ( ; *text; text++, x += (float)( FNT_CELL_W * scale ) )
	{
		ch = (unsigned char)*text;
		if ( ch >= 'a' && ch <= 'z' )
		{
			ch -= 'a' - 'A';
		}
		if ( ch < FNT_FIRST || ch > FNT_LAST )
		{
			ch = '?';
		}
		g = fnt_glyphs[ch - FNT_FIRST];
		for ( row = 0; row < 7; row++ )
		{
			for ( col = 0; col < 5; col += run ? run : 1 )
			{
				run = 0;
				while ( col + run < 5 && ( g[row] & ( 0x10 >> ( col + run ) ) ) )
				{
					run++;
				}
				if ( run )
				{
					r.x = x + (float)( col * scale );
					r.y = y + (float)( row * scale );
					r.w = (float)( run * scale );
					r.h = (float)scale;
					SDL_RenderFillRectF( ren, &r );
				}
			}
		}
	}
}

/**
  * @brief  Width of a string in pixels.
  *
  * @param  scale Pixel size of one font dot.
  * @param  text NUL terminated string.
  *
  * @retval Width in pixels, 0 for an empty string.
  */
int fnt_width( int scale, const char *text )
{
	int n = (int)strlen( text );

	return n ? ( n * FNT_CELL_W - 1 ) * scale : 0;
}
